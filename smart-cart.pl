start :-
    write("Dzień dobry, w czym mogę Panu/Pani pomóc?"), nl,
    start([]).

start(Koszyk) :-
    write("Wybierz kategorie, ktora Cie interesuje: 1-warzywa, 2-owoce, 3-nabial, 4-mieso, 5-pieczywo, 6-napoje, 7-przekaski, 8-produkty zbożowe"), nl,
    read(Numer_kategorii),
    sprawdzenie_wprowadzonych_danych(Numer_kategorii, Kategoria, Koszyk),
    write("Podaj numer produktu, który chcesz dodać do wózka (1-10)"), nl,
    read(Numer),
    dodaj_do_koszyka_produkt(Numer, Kategoria, Koszyk, NowyKoszyk), nl,
    wyswietl_koszyk(NowyKoszyk), nl,
    czy_chcesz_kontynuowac_zakupy(NowyKoszyk).

sprawdzenie_wprowadzonych_danych(Numer_kategorii, Kategoria, Koszyk) :-
    (   \+ integer(Numer_kategorii) ->
            write("Błędne dane - nie jest liczbą"), nl,
            start(Koszyk)
    ;   Numer_kategorii < 1 ; Numer_kategorii > 9 ->
            write("Błędne dane - numer kategorii musi być w zakresie 1-8"), nl,
            start(Koszyk)
    ;   produkt(Numer_kategorii, _, Kategoria, _, _, _, _) ->
            write("Wybrano kategorię: "), write(Kategoria), nl,
            (
                (Numer_kategorii =:= 1, Kategoria == warzywa);
                (Numer_kategorii =:= 2, Kategoria == owoce);
                (Numer_kategorii =:= 3, Kategoria == nabial);
                (Numer_kategorii =:= 4, Kategoria == mieso);
                (Numer_kategorii =:= 5, Kategoria == pieczywo);
                (Numer_kategorii =:= 6, Kategoria == napoje);
                (Numer_kategorii =:= 7, Kategoria == przekaski);
                (Numer_kategorii =:= 8, Kategoria == zbozowe)
            ) -> wyszukaj_kategorie(Kategoria)
    ;   write("Błędna kategoria dla tego numeru"), nl, start(Koszyk)
    ).

wyszukaj_kategorie(Kategoria) :-
    produkt(_, Numer, Kategoria, Nazwa, Firma, Kraj_Pochodzenia, Cena),
    write("Numer: "), write(Numer), nl,
    write(" Nazwa produktu: "), write(Nazwa),
    write(" | Firma: "), write(Firma),
    write(" | Kraj Pochodzenia: "), write(Kraj_Pochodzenia),
    write(" | Cena: "), write(Cena), write("zł"), nl, fail.
wyszukaj_kategorie(_).

dodaj_do_koszyka_produkt(Numer, Kategoria, Koszyk, NowyKoszyk) :-
    \+ integer(Numer) -> write("Błędne dane - nie jest liczbą"), nl, start(Koszyk);
    (Numer > 10 ; Numer < 1) -> write("Błędne dane"), nl, start(Koszyk);
    (
        produkt(_, Numer, Kategoria, Nazwa, _, _, _),
        append(Koszyk, [Nazwa], NowyKoszyk),
        write("Dodano do koszyka: "), write(Nazwa)
    ).

wyswietl_koszyk(Koszyk) :-
    write("Koszyk zawiera: "), write(Koszyk).

czy_chcesz_kontynuowac_zakupy(Koszyk) :-
    write("Czy chcesz kontynuować zakupy? (tak/nie)"), nl,
    read(Odpowiedz),
    (
        Odpowiedz == tak -> start(Koszyk);
        Odpowiedz == nie -> prekoniec(Koszyk);
        write("Błąd, wpisz ponownie"), nl, czy_chcesz_kontynuowac_zakupy(Koszyk)
    ).

prekoniec(Koszyk) :-
    write("Hej, a może coś weźmiesz z podanych propozycji? Program automatycznie doda Ci brakujące produkty do koszyka"), nl,
    wyswietl_propozycje_dan(Koszyk, MAX_pozycja, BrakujaceDANE),
    odwroc_i_usun_pierwszy(BrakujaceDANE, OdwroconeBezPierwszego),
    zapytanie_walidacja_danych_prekoniec(Koszyk, MAX_pozycja, OdwroconeBezPierwszego), !.

wyswietl_propozycje_dan(Koszyk, MAX_pozycja, BrakujaceDANE) :-
    zbierz_dania_rekomendowane(Koszyk, [], Dania),
    sort(Dania, PosortowaneDania),
    wyswietl_posortowane_propozycje(PosortowaneDania, Koszyk, 0, 1, MAX_pozycja, BrakujaceDANE).

odwroc_i_usun_pierwszy(BrakujaceDANE, OdwroconeBezPierwszego) :-
    reverse(BrakujaceDANE, Odwrocone),
    select(_, Odwrocone, OdwroconeBezPierwszego).

zapytanie_walidacja_danych_prekoniec(Koszyk, MAX_pozycja, BrakujaceDANE) :-
    (
        MAX_pozycja =:= 0 -> koniec(Koszyk);
        (
            MAX_pozycja =:= 1 -> write("Wybierz numer 1 lub wpisz 4, jeżeli nie chcesz nic dodawać."), nl;
            MAX_pozycja > 1 -> write("Wybierz numer 1-"), write(MAX_pozycja), write(" lub wpisz 4, jeżeli nie chcesz nic dodawać."), nl
        ),
        read(Numer),
        (
            \+ integer(Numer) -> write("Błędne dane - nie jest liczbą"), nl, zapytanie_walidacja_danych_prekoniec(Koszyk, MAX_pozycja, BrakujaceDANE);
            (Numer =< MAX_pozycja, MAX_pozycja > 0) -> (
                member((Numer, Brakujace, _Nazwa), BrakujaceDANE),
                write("Wybrałeś "), write(Brakujace), write(" dodaję do koszyka."), nl,
                dodaj_brakujace_skladniki(Koszyk, Brakujace)
            );
            Numer =:= 4 -> koniec(Koszyk)
        )
    ).

zbierz_dania_rekomendowane(Koszyk, Propozycje, Wynik) :-
    (
        danie(Nazwa, Lista_produktow),
        subtract(Lista_produktow, Koszyk, Brakujace),
        length(Brakujace, Dl_brakujacych),
        \+ member((Dl_brakujacych, Nazwa, Lista_produktow), Propozycje),
        zbierz_dania_rekomendowane(Koszyk, [(Dl_brakujacych, Nazwa, Lista_produktow) | Propozycje], Wynik)
    ;
        Wynik = Propozycje
    ).

wyswietl_posortowane_propozycje([], _, Licznik, _, Licznik, []) :- !.
wyswietl_posortowane_propozycje(_, _, Licznik, _, Licznik, [_]) :-
    Licznik >= 3, !.
wyswietl_posortowane_propozycje([(_, Nazwa, Lista_produktow) | Reszta], Koszyk, Licznik, Numer, MAX_pozycja, [(Numer, Brakujace, Nazwa) | BrakujaceDANE]) :-
    intersection(Lista_produktow, Koszyk, Pasujace),
    length(Pasujace, Dl_pasujace),
    subtract(Lista_produktow, Koszyk, Brakujace),
    length(Brakujace, Dl_brakujacych),
    (
        (Brakujace \= [], Dl_brakujacych =< 3, Dl_pasujace >= 2) ->
            write(Numer), write(". "),
            write("Brakuje: "), write(Brakujace),
            write(", aby zrobić danie: "), write(Nazwa), write(", składniki: "), write(Lista_produktow), nl,
            NewLicznik is Licznik + 1,
            NewNumer is Numer + 1,
            wyswietl_posortowane_propozycje(Reszta, Koszyk, NewLicznik, NewNumer, MAX_pozycja, BrakujaceDANE)
    ;
        wyswietl_posortowane_propozycje(Reszta, Koszyk, Licznik, Numer, MAX_pozycja, BrakujaceDANE)
    ).

dodaj_brakujace_skladniki(Koszyk, Brakujace) :-
    append(Brakujace, Koszyk, NowyKoszyk),
    koniec(NowyKoszyk).

koniec(Koszyk) :-
    write("============================"), nl,
    write("PODSUMOWANIE"), nl,
    write("============================"), nl,
    write("Zawartość koszyka: "), write(Koszyk), nl,
    oblicz_cene(Koszyk),
    write("Dziękujemy za zakupy i zapraszamy ponownie! :)"), abort.

oblicz_cene(Koszyk) :-
    oblicz_sume_z_produktow(Koszyk, 0, Suma),
    zaokraglij_cene(Suma, Wynik_ostateczny),
    write("Całkowita cena za zakupy wynosi: "), write(Wynik_ostateczny), write(" zł"), nl.

oblicz_sume_z_produktow([], SumaKoncowa, SumaKoncowa).
oblicz_sume_z_produktow([Nazwa | Reszta], AktualnaCena, SumaKoncowa) :-
    produkt(_, _, _, Nazwa, _, _, Cena),
    NowaAktualnaCena is AktualnaCena + Cena,
    oblicz_sume_z_produktow(Reszta, NowaAktualnaCena, SumaKoncowa).

zaokraglij_cene(Suma, Wynik_ostateczny) :-
    Temp is Suma * 100,
    TempR is round(Temp),
    Wynik_ostateczny is TempR / 100.